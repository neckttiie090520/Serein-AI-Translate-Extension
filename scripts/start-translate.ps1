#Requires -Version 5.1
<#
.SYNOPSIS
  Start, stop, monitor or autostart the local LTEngine translation server.
  The engine always runs fully in the background: no console window, no
  taskbar button. Output goes to %LOCALAPPDATA%\SereinTranslate\engine.log.
.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\start-translate.ps1             # start hidden, wait until ready
.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\start-translate.ps1 -Status
.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\start-translate.ps1 -Stop
.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\start-translate.ps1 -Install    # autostart at login (Task Scheduler)
.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\start-translate.ps1 -Uninstall  # remove the autostart task
#>
[CmdletBinding()]
param(
    [switch]$HelpOnly,
    [switch]$Stop,
    [switch]$Status,
    [switch]$Install,
    [switch]$Uninstall,
    # Internal: used by the autostart task. Same as a manual start, but quiet
    # and logging to autostart.log instead of the console.
    [switch]$Background,
    [int]$Port = 0
)

$ErrorActionPreference = 'Stop'

$TaskName  = 'SereinTranslateEngine'
$DataDir   = Join-Path $env:LOCALAPPDATA 'SereinTranslate'
$ConfigPath = Join-Path $DataDir 'config.json'
$LogOut    = Join-Path $DataDir 'engine.log'
$LogErr    = Join-Path $DataDir 'engine.err'
$AutoLog   = Join-Path $DataDir 'autostart.log'
$VbsPath   = Join-Path $DataDir 'engine-background.vbs'

if ($HelpOnly) {
    Write-Host 'Usage: powershell -File scripts\start-translate.ps1 [-Status | -Stop | -Install | -Uninstall | -Port <n>]'
    Write-Host 'Default action starts the engine hidden and waits until the port answers.'
    Write-Host ('Config: ' + $ConfigPath + ' (written by setup-translate.ps1)')
    Write-Host ('Logs:   ' + $LogOut + ' / ' + $LogErr)
    exit 0
}

function Test-Port([string]$HostName, [int]$PortNumber) {
    $client = New-Object System.Net.Sockets.TcpClient
    try {
        $async = $client.BeginConnect($HostName, $PortNumber, $null, $null)
        return ($async.AsyncWaitHandle.WaitOne(700) -and $client.Connected)
    } catch {
        return $false
    } finally {
        $client.Close()
    }
}

function Say([string]$Message) {
    if ($Background) {
        ('[{0}] {1}' -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), $Message) |
            Add-Content -Path $AutoLog -Encoding ASCII
    } else {
        Write-Host $Message
    }
}

function Fail([string]$Message) {
    if ($Background) {
        ('[{0}] {1}' -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), $Message) |
            Add-Content -Path $AutoLog -Encoding ASCII
    } else {
        Write-Host $Message -ForegroundColor Red
    }
    exit 1
}

function Get-EngineProcess {
    Get-CimInstance Win32_Process -Filter "Name = 'ltengine.exe'" -ErrorAction SilentlyContinue |
        ForEach-Object { Get-Process -Id $_.ProcessId -ErrorAction SilentlyContinue }
}

function Rotate-Log([string]$Path) {
    if ((Test-Path $Path) -and ((Get-Item $Path).Length -gt 5MB)) {
        Remove-Item ($Path + '.old') -Force -ErrorAction SilentlyContinue
        Move-Item $Path ($Path + '.old') -Force
    }
}

if (-not (Test-Path $ConfigPath)) {
    Fail ('No config found at ' + $ConfigPath + '. Run scripts\setup-translate.ps1 first.')
}
$config = Get-Content $ConfigPath -Raw | ConvertFrom-Json
if ($Port -le 0) { $Port = [int]$config.port }

if ($Uninstall) {
    $task = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
    if ($task) {
        Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
        Say ('Removed scheduled task ' + $TaskName)
    } else {
        Say ('No scheduled task named ' + $TaskName)
    }
    if (Test-Path $VbsPath) { Remove-Item $VbsPath -Force }
    Say 'Autostart removed. A running engine is left alone; stop it with -Stop.'
    exit 0
}

if ($Install) {
    New-Item -ItemType Directory -Force -Path $DataDir | Out-Null
    $runLine = 'powershell.exe -NoProfile -ExecutionPolicy Bypass -File "{0}" -Background' -f $PSCommandPath
    # Build the statement outside the array literal: Windows PowerShell 5.1
    # parses `'a' + $b + 'c'` INSIDE @(...) as three separate elements, which
    # wrote a syntactically broken multi-line VBS. Concatenate first, then list.
    $runStmt = 'CreateObject("WScript.Shell").Run "' + ($runLine -replace '"', '""') + '", 0, True'
    $vbs = @(
        "' Generated by Serein scripts\start-translate.ps1 -Install. Regenerate any time with -Install.",
        "' Launches the engine starter with no console window at all.",
        $runStmt
    )
    Set-Content -Path $VbsPath -Value $vbs -Encoding ASCII

    $action   = New-ScheduledTaskAction -Execute 'wscript.exe' -Argument ('//B //Nologo "{0}"' -f $VbsPath)
    # A trigger for the current user only, plus an Interactive principal, so
    # registering needs no elevation; an any-user logon trigger would.
    $me       = "$env:USERDOMAIN\$env:USERNAME"
    $trigger  = New-ScheduledTaskTrigger -AtLogOn -User $me
    # The GPU driver can take a moment after login; starting too early makes
    # the Vulkan device query fail, so the task fires 30 seconds in.
    $trigger.Delay = 'PT30S'
    $settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
        -ExecutionTimeLimit ([TimeSpan]::Zero) -MultipleInstances IgnoreNew -StartWhenAvailable `
        -RestartCount 3 -RestartInterval (New-TimeSpan -Minutes 1)
    $principal = New-ScheduledTaskPrincipal -UserId $me -LogonType Interactive -RunLevel Limited
    Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Settings $settings `
        -Principal $principal `
        -Description 'Starts the hidden Serein Translate engine (LTEngine) for this user.' -Force | Out-Null
    Say ('Installed. The engine starts hidden ~30 s after login (Task Scheduler: ' + $TaskName + ').')
    Say ('Manual control: -Status / -Stop / -Uninstall.  Logs: ' + $LogOut)
    exit 0
}

if ($Status) {
    $listening = Test-Port $config.host $Port
    $engine = Get-EngineProcess
    $task = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
    Write-Host ('Engine   : ' + $(if ($listening) { 'listening on ' + $config.host + ':' + $Port } else { 'down' }))
    Write-Host ('Process  : ' + $(if ($engine) { ($engine | ForEach-Object { 'ltengine pid ' + $_.Id } ) -join ', ' } else { 'not running' }))
    Write-Host ('Autostart: ' + $(if ($task) { 'installed (' + $TaskName + ', at logon +30 s, hidden)' } else { 'not installed (-Install to add)' }))
    Write-Host ('Config   : ' + $ConfigPath)
    if (Test-Path $LogErr) {
        $tail = Get-Content $LogErr -Tail 5 -ErrorAction SilentlyContinue
        if ($tail) { Write-Host 'engine.err (last lines):'; $tail | ForEach-Object { Write-Host ('  ' + $_) } }
    }
    exit 0
}

if ($Stop) {
    # The autostart task (if running) owns the engine's process tree; stop it
    # first so it does not restart the engine out from under us.
    Stop-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
    $owners = Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue |
        Select-Object -ExpandProperty OwningProcess -Unique
    $stopped = @()
    foreach ($owner in $owners) {
        $proc = Get-Process -Id $owner -ErrorAction SilentlyContinue
        if ($proc -and $proc.ProcessName -eq 'ltengine') { Stop-Process -Id $owner -Force; $stopped += $owner }
    }
    Get-EngineProcess | Where-Object { $stopped -notcontains $_.Id } | Stop-Process -Force
    Say ('Engine stopped. (' + $(if ($stopped) { 'pid ' + ($stopped -join ', ') } else { 'no listener on ' + $Port }) + ')')
    exit 0
}

if (Test-Port $config.host $Port) {
    Say ('Engine already listening on ' + $config.host + ':' + $Port)
    exit 0
}

if (-not (Test-Path $config.engineExe)) {
    Fail ('Engine executable missing: ' + $config.engineExe)
}
if (-not (Test-Path $config.modelFile)) {
    Fail ('Model file missing: ' + $config.modelFile)
}

Rotate-Log $LogOut
Rotate-Log $LogErr
Say ('Starting LTEngine hidden on ' + $config.host + ':' + $Port + ' (model load can take up to a minute)...')
$engineArgs = '--host "{0}" --port {1} --model-file "{2}"' -f $config.host, $Port, $config.modelFile
$process = Start-Process -FilePath $config.engineExe -ArgumentList $engineArgs `
    -WindowStyle Hidden -RedirectStandardOutput $LogOut -RedirectStandardError $LogErr -PassThru

$deadline = (Get-Date).AddSeconds(180)
while ((Get-Date) -lt $deadline) {
    Start-Sleep -Seconds 2
    if ($process.HasExited) {
        Say ('Engine exited immediately with code ' + $process.ExitCode + '. Last engine.err lines:')
        if (Test-Path $LogErr) { Get-Content $LogErr -Tail 10 | ForEach-Object { Say ('  ' + $_) } }
        Say ('Run it manually to debug: ' + $config.engineExe + ' ' + $engineArgs)
        exit 1
    }
    if (Test-Port $config.host $Port) {
        Say ('Translation engine ready on ' + $config.host + ':' + $Port + ' (hidden, pid ' + $process.Id + ')')
        if ($Background) {
            # Stay alive for the engine's lifetime: the autostart task owns this
            # process tree, and exiting here would let Task Scheduler tear the
            # job down and kill the engine with it. The engine's exit code
            # propagates so the task can restart it (RestartCount).
            $process.WaitForExit()
            exit $process.ExitCode
        }
        exit 0
    }
}
Fail ('Timed out waiting for the engine port. Last engine.err lines: ' + $(if (Test-Path $LogErr) { (Get-Content $LogErr -Tail 5) -join ' | ' } else { 'none' }))
